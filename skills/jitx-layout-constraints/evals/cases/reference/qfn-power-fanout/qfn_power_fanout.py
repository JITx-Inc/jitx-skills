QFN_LEAD_COUNT = 32  # skill default: 32 leads for the placeholder QFN
QFN_NAMED_PIN_COUNT = 2  # skill default: 2 named power pins in the placeholder
QFN_PITCH_MM = 0.5  # skill default: 0.5 mm pitch required by this reference
QFN_LEAD_SPAN_MM = 5.0  # skill default: 5.0 mm placeholder lead span
QFN_LEAD_LENGTH_MM = 0.35  # skill default: 0.35 mm placeholder lead length
QFN_LEAD_WIDTH_MM = 0.33  # skill default: 0.33 mm placeholder lead width
QFN_BODY_WIDTH_MM = 5.0  # skill default: 5.0 mm placeholder body width
QFN_BODY_LENGTH_MM = 5.0  # skill default: 5.0 mm placeholder body length
QFN_BODY_HEIGHT_MM = 0.9  # skill default: 0.9 mm placeholder body height

SOURCE_PAD_WIDTH_MM = 1.0  # skill default: 1.0 mm source-connector pad width
SOURCE_PAD_PITCH_MM = 2.0  # skill default: 2.0 mm source-connector pad pitch
SOURCE_COURTYARD_WIDTH_MM = 4.0  # skill default: 4.0 mm courtyard width
SOURCE_COURTYARD_HEIGHT_MM = 2.0  # skill default: 2.0 mm courtyard height

BOARD_WIDTH_MM = 20.0  # skill default: 20.0 mm reference-board width
BOARD_HEIGHT_MM = 20.0  # skill default: 20.0 mm reference-board height
DEFAULT_TRACE_WIDTH_MM = 0.125  # skill default: 0.125 mm signal width
DEFAULT_CLEARANCE_MM = 0.125  # skill default: 0.125 mm copper clearance
THERMAL_GAP_MM = 0.125  # skill default: 0.125 mm thermal gap
THERMAL_SPOKE_WIDTH_MM = 0.2  # skill default: 0.2 mm thermal spoke width
THERMAL_SPOKE_COUNT = 4  # skill default: 4 thermal spokes
POUR_FEATURE_WIDTH_MM = 0.2  # skill default: 0.2 mm pour feature width
POWER_CLASS_WIDTH_MM = 0.5  # skill default: 0.5 mm power-class width
ESCAPE_CLEARANCE_MARGIN_MM = 0.01  # skill default: 0.01 mm above the fab floor
ESCAPE_RUN_MM = 1.0  # skill default: 1.0 mm from pad edge to transition
GEOMETRY_TOLERANCE_MM = 1e-6  # skill default: 1e-6 mm geometry comparison


class PowerTag(Tag):
    """Power-class nets."""


class EscapeTag(Tag):
    """Base class for local package-escape segments."""


class QfnEscapeTag(EscapeTag):
    """Escape segment into the placeholder QFN power pad."""


class SourcePad(Pad):
    shape = rectangle(SOURCE_PAD_WIDTH_MM, SOURCE_PAD_WIDTH_MM)
    soldermask = Soldermask(shape)
    paste = Paste(shape)


class SourceLandpattern(Landpattern):
    p = [
        SourcePad().at(-SOURCE_PAD_PITCH_MM / 2.0, 0.0),
        SourcePad().at(SOURCE_PAD_PITCH_MM / 2.0, 0.0),
    ]
    courtyard = Courtyard(
        rectangle(SOURCE_COURTYARD_WIDTH_MM, SOURCE_COURTYARD_HEIGHT_MM)
    )


class PowerSource(Component):
    """Placeholder source connector (skill default: 2 pins)."""

    reference_designator_prefix = "J"
    V5 = Port()
    GND = Port()
    landpattern = SourceLandpattern()
    symbol = BoxSymbol(rows=Row(left=PinGroup(V5), right=PinGroup(GND)))


class PlaceholderQfn32(Component):
    """Placeholder QFN (skill default: 32 leads), not an orderable part."""

    reference_designator_prefix = "U"
    VDD = Port()
    GND = Port()
    NC = [Port() for _ in range(QFN_LEAD_COUNT - QFN_NAMED_PIN_COUNT)]

    landpattern = (
        QFN(num_leads=QFN_LEAD_COUNT)
        .lead_profile(
            LeadProfile(
                span=Toleranced.exact(QFN_LEAD_SPAN_MM),
                pitch=QFN_PITCH_MM,
                type=QFNLead(
                    length=Toleranced.exact(QFN_LEAD_LENGTH_MM),
                    width=Toleranced.exact(QFN_LEAD_WIDTH_MM),
                ),
            )
        )
        .package_body(
            RectanglePackage(
                width=Toleranced.exact(QFN_BODY_WIDTH_MM),
                length=Toleranced.exact(QFN_BODY_LENGTH_MM),
                height=Toleranced.exact(QFN_BODY_HEIGHT_MM),
            )
        )
        .density_level(DensityLevel.C)
    )
    symbol = BoxSymbol(
        rows=Row(
            left=PinGroup(VDD, *NC[: QFN_LEAD_COUNT // 2 - 1]),
            right=PinGroup(GND, *NC[QFN_LEAD_COUNT // 2 - 1 :]),
        )
    )

    def __init__(self):
        entries: list[tuple[Port, Pad]] = [
            (self.VDD, self.landpattern.p[1]),  # skill default: VDD is pad 1
            (self.GND, self.landpattern.p[2]),  # skill default: GND is pad 2
        ]
        entries.extend(
            (port, self.landpattern.p[pad_number])
            for pad_number, port in enumerate(self.NC, start=3)  # skill default: pad 3 starts NC
        )
        self.mappings = [PadMapping(entries)]
        for port in self.NC:
            port.no_connect()


class ReferenceBoard(Board):
    shape = rectangle(BOARD_WIDTH_MM, BOARD_HEIGHT_MM)


@dataclass(frozen=True)
class EscapeGeometry:
    pad_width: float
    adjacent_gap: float
    row_pitch: float
    pad_depth: float
    escape_width: float
    escape_clearance: float
    pad_center: tuple[float, float]
    transition: tuple[float, float]


def one_pad(mapping: PadMapping, port: Port) -> Pad:
    """Return the one landpattern pad mapped to ``port``."""

    pads = mapping[port]
    if isinstance(pads, Pad):
        return pads
    if len(pads) != 1:  # skill default: 1 pad maps to the selected port
        raise AssertionError(f"expected one pad for {port}, got {len(pads)}")
    return pads[0]


def _pad_copper_by_identity(
    design: Design, landpattern: Landpattern
) -> dict[int, BaseGeometry]:
    """Read placed top-copper pad polygons through the Pad to Copper query."""

    pads = list(pad for _, pad in visit(landpattern, Pad))
    pad_ids = {id(pad) for pad in pads}
    grouped: dict[int, list[BaseGeometry]] = {id(pad): [] for pad in pads}
    for trace, copper in query(design, Copper):
        parent_id = id(trace.parent)
        if parent_id not in pad_ids or copper.layer != 0:
            continue
        if trace.transform is None:
            raise ValueError(f"unresolved pad frame at {trace.path}")
        grouped[parent_id].append(copper.shape.at(trace.transform).to_shapely().g)

    result: dict[int, BaseGeometry] = {}
    for pad_id, shapes in grouped.items():
        if not shapes:
            raise ValueError("pad query returned no top-copper geometry")
        result[pad_id] = unary_union(shapes)
    return result


def derive_qfn_escape_geometry(
    design: Design,
    component: PlaceholderQfn32,
    target_pad: Pad,
    fab: FabricationConstraints,
) -> EscapeGeometry:
    """Derive the QFN row gap, pad width, and legal escape width."""

    pad_copper = _pad_copper_by_identity(design, component.landpattern)
    target = pad_copper[id(target_pad)]
    minx, miny, maxx, maxy = target.bounds
    center = ((minx + maxx) / 2.0, (miny + maxy) / 2.0)

    if component.transform is None:
        raise ValueError("QFN placement is unresolved")
    component_center = component.transform.translation
    delta = (center[0] - component_center[0], center[1] - component_center[1])
    radial_is_x = abs(delta[0]) >= abs(delta[1])
    radial_index = 0 if radial_is_x else 1
    tangent_index = 1 - radial_index
    target_radial = center[radial_index]

    row_neighbors: list[tuple[float, BaseGeometry, tuple[float, float]]] = []
    for pad_id, geometry in pad_copper.items():
        if pad_id == id(target_pad):
            continue
        gx0, gy0, gx1, gy1 = geometry.bounds
        candidate_center = ((gx0 + gx1) / 2.0, (gy0 + gy1) / 2.0)
        if not isclose(
            candidate_center[radial_index],
            target_radial,
            abs_tol=GEOMETRY_TOLERANCE_MM,
        ):
            continue
        tangent_delta = abs(candidate_center[tangent_index] - center[tangent_index])
        row_neighbors.append((tangent_delta, geometry, candidate_center))

    if not row_neighbors:
        raise ValueError("QFN target pad has no adjacent pad in its row")
    row_pitch, neighbor, _ = min(row_neighbors, key=lambda item: item[0])
    pad_width = (maxy - miny) if radial_is_x else (maxx - minx)
    pad_depth = (maxx - minx) if radial_is_x else (maxy - miny)
    adjacent_gap = row_pitch - pad_width
    if not isclose(
        adjacent_gap,
        target.distance(neighbor),
        abs_tol=GEOMETRY_TOLERANCE_MM,
    ):
        raise ValueError("QFN row pads are not a uniform pitch-minus-width channel")

    fab_floor = fab.min_copper_copper_space
    centered_channel_limit = pad_width + 2.0 * (adjacent_gap - fab_floor)
    escape_width = min(pad_width, centered_channel_limit)
    if escape_width < fab.min_copper_width:
        raise ValueError(
            "derived QFN escape is below the substrate minimum copper width"
        )
    escape_clearance = fab_floor + ESCAPE_CLEARANCE_MARGIN_MM

    if radial_is_x:
        outward = (-1.0 if delta[0] < 0.0 else 1.0, 0.0)
    else:
        outward = (0.0, -1.0 if delta[1] < 0.0 else 1.0)
    run = pad_depth / 2.0 + ESCAPE_RUN_MM
    transition = (center[0] + outward[0] * run, center[1] + outward[1] * run)

    return EscapeGeometry(
        pad_width=pad_width,
        adjacent_gap=adjacent_gap,
        row_pitch=row_pitch,
        pad_depth=pad_depth,
        escape_width=escape_width,
        escape_clearance=escape_clearance,
        pad_center=center,
        transition=transition,
    )


def realized_route_widths(route: Route) -> tuple[float, ...]:
    """Return every captured ArcPolyline or Polyline width for ``route``."""

    if not route.traces:
        return ()
    widths: list[float] = []
    for trace in route.traces:
        for shape in trace.shapes:
            primitive = shape.to_primitive().geometry
            if isinstance(primitive, ArcPolyline | Polyline):
                widths.append(primitive.width)
    return tuple(widths)


class FanoutCircuit(Circuit):
    def __init__(self):
        self.source = PowerSource().at(-7.0, 0.0)
        self.u1 = PlaceholderQfn32().at(0.0, 0.0)
        self.v5 = Net([self.source.V5, self.u1.VDD], name="5V")
        self.gnd = Net([self.source.GND, self.u1.GND], name="GND")
        Tags(PowerTag()).assign(self.v5)

    @Design.Initialized.on
    def make_escape(self, initialized: Design.Initialized):
        target_pad = one_pad(self.u1.mappings[0], self.u1.VDD)
        self.escape_geometry = derive_qfn_escape_geometry(
            initialized.design,
            self.u1,
            target_pad,
            initialized.design.substrate.constraints,
        )
        self.route_point = RoutePoint(layer=0).at(self.escape_geometry.transition)
        self.v5 += self.route_point.port
        self.trunk_route = Route(self.source.V5, self.route_point, layer=0)
        self.escape_route = Route(
            self.route_point,
            target_pad,
            layer=0,
            sketch=[self.escape_geometry.transition, self.escape_geometry.pad_center],
        )
        Tags(QfnEscapeTag()).assign(self.escape_route)
        self.escape_rules = [
            design_constraint(QfnEscapeTag(), priority=3).trace_width(
                self.escape_geometry.escape_width
            ),
            design_constraint(
                QfnEscapeTag(), AnyObject, priority=3
            ).clearance(self.escape_geometry.escape_clearance),
        ]
        print(
            "QFN escape geometry: "
            f"pad_width={self.escape_geometry.pad_width:.6f} mm, "
            f"adjacent_gap={self.escape_geometry.adjacent_gap:.6f} mm, "
            f"row_pitch={self.escape_geometry.row_pitch:.6f} mm, "
            f"escape_width={self.escape_geometry.escape_width:.6f} mm, "
            f"escape_clearance={self.escape_geometry.escape_clearance:.6f} mm"
        )


class QfnPowerFanoutDesign(Design):
    substrate = JLC04161H_7628()
    board = ReferenceBoard()
    circuit = FanoutCircuit()

    def __init__(self):
        fab = self.substrate.constraints
        default_width = max(fab.min_copper_width, DEFAULT_TRACE_WIDTH_MM)
        default_clearance = max(
            fab.min_copper_copper_space, DEFAULT_CLEARANCE_MM
        )
        thermal_gap = max(fab.min_copper_copper_space, THERMAL_GAP_MM)
        thermal_spoke = max(fab.min_copper_width, THERMAL_SPOKE_WIDTH_MM)
        pour_feature = max(fab.min_copper_width, POUR_FEATURE_WIDTH_MM)

        # Priority ladder: board defaults 0, power class 2, QFN escape 3.
        self.rules = [  # skill default: 4 board rules, then the class rule
            design_constraint(IsTrace).trace_width(default_width),
            design_constraint(IsCopper, IsCopper).clearance(default_clearance),
            design_constraint(IsPad).thermal_relief(
                thermal_gap, thermal_spoke, THERMAL_SPOKE_COUNT
            ),
            design_constraint(IsPour).pour_feature_size(pour_feature),
            design_constraint(PowerTag(), priority=2).trace_width(
                POWER_CLASS_WIDTH_MM
            ),
        ]


